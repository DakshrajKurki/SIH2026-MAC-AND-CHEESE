"""Run every TrustLens pilot benchmark and write results/SUMMARY.md.

    pip install -r requirements.txt
    python run_all.py          # ~15-25 min on a laptop CPU

Experiment 2 reuses the models saved by Experiment 1, so the order matters.
"""
import json, os, runpy, time
from common import RESULTS_DIR

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENTS = ["exp1_contributor_poisoning.py", "exp2_neural_cleanse.py", "exp3_drift.py", "exp4_sealing.py"]


def load(name):
    with open(os.path.join(RESULTS_DIR, name)) as f:
        return json.load(f)["summary"]


if __name__ == "__main__":
    for exp in EXPERIMENTS:
        t0 = time.time()
        print(f"\n=== {exp} ===")
        runpy.run_path(os.path.join(HERE, exp), run_name="__main__")
        print(f"--- {exp} finished in {time.time() - t0:.0f}s")

    e1, e2 = load("exp1_contributor_poisoning.json"), load("exp2_neural_cleanse.json")
    e3, e4 = load("exp3_drift.json"), load("exp4_sealing.json")
    pct = lambda v: f"{100 * v:.1f}%"
    md = f"""# TrustLens pilot benchmark results

Generated by `python run_all.py` (Fashion-MNIST, small CNN, 5 contributors, seeds 0-2). Raw numbers per seed are in the JSON files next to this one.

| # | What was measured | Result |
|---|---|---|
| 1 | Malicious contributor identified and quarantined (only it) | **{e1['malicious_contributor_isolated']}** runs |
| 1 | Backdoor attack success: before -> after quarantine | **{pct(e1['attack_success_before_mean'])} -> {pct(e1['attack_success_after_mean'])}** |
| 1 | Clean accuracy: unattacked / poisoned / after quarantine | {pct(e1['clean_accuracy_unattacked_mean'])} / {pct(e1['clean_accuracy_poisoned_mean'])} / **{pct(e1['clean_accuracy_after_quarantine_mean'])}** |
| 2 | Attacked class pinpointed in delivered model (Neural Cleanse) | **{e2['attacked_class_pinpointed']}** |
| 2 | False alarms on unattacked models | {e2['false_alarms_on_unattacked_models']} |
| 3 | Drifted batches detected / false-alarm rate on clean batches | **{pct(e3['drifted_batches_detected_mean'])}** / {pct(e3['false_alarm_rate_mean'])} |
| 4 | Time to seal one 640x640 frame (SHA-256 + Ed25519) | **{e4['seal_ms_per_frame_mean']} ms** |
| 4 | Single-byte tampers caught | **{e4['tampers_caught']}** |
| 4 | Full re-verification of a 10,000-record signed ledger | **{e4['ledger_full_verify_seconds']} s** |
"""
    with open(os.path.join(RESULTS_DIR, "SUMMARY.md"), "w") as f:
        f.write(md)
    print(md)
